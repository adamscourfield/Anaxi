-- Remove deprecated legacy SignalKey enum values. Postgres has no direct
-- "DROP VALUE" for enums, so recreate the type without them and repoint the
-- one column that uses it. Any Insight row still pointing at a removed value
-- is dropped first so the type swap below can't fail on it.
DELETE FROM "Insight" WHERE "signalKey"::text IN (
  'COLD_CALL_DENSITY',
  'LANGUAGE_PRECISION',
  'LIVE_ADJUSTMENT',
  'RETRIEVAL_PRESENCE',
  'STRETCH_DEPLOYMENT',
  'INDEPENDENT_ACCOUNTABILITY',
  'ERROR_CORRECTION_DEPTH',
  'PARTICIPATION_EQUITY'
);

ALTER TYPE "SignalKey" RENAME TO "SignalKey_old";

CREATE TYPE "SignalKey" AS ENUM (
  'BEHAVIOUR_CLIMATE',
  'PACE_MOMENTUM',
  'ENTRY_ROUTINE',
  'RETRIEVAL_TASK_QUALITY',
