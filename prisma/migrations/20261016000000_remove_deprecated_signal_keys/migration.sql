  'CFU_CYCLES',
  'RESPONSIVE_ADJUSTMENT',
  'ERROR_CORRECTION_PRECISION',
  'MODELLING_ON_DEMAND',
  'PARTICIPATION_EQUITY_GP',
  'TASK_CLARITY',
  'INDEPENDENT_ACCOUNTABILITY_IP',
  'CIRCULATION_FEEDBACK',
  'STRETCH_DEPLOYMENT_IP',
  'SILENCE_AND_FOCUS',
  'PRESENTATION_STANDARD',
  'WORK_COMPLETION',
  'SUSTAINED_EFFORT',
