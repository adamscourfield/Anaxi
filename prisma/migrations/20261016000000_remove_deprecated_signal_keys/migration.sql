-- AlterTable: repoint Insight.signalKey at the new enum type.
ALTER TABLE "Insight" ALTER COLUMN "signalKey" TYPE "SignalKey" USING ("signalKey"::text::"SignalKey");

DROP TYPE "SignalKey_old";

-- Drop tenant signal-label rows for the removed legacy keys (TenantSignalLabel.signalKey is a
-- free-text column, so it isn't affected by the enum change above, but these rows are now orphaned).
DELETE FROM "TenantSignalLabel" WHERE "signalKey" IN (
  'COLD_CALL_DENSITY',
  'LANGUAGE_PRECISION',
  'LIVE_ADJUSTMENT',
